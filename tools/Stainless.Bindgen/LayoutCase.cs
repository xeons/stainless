using System.Text;

namespace Stainless.Bindgen;

/// <summary>
/// The end-to-end case that holds the bindings to what clang says: an
/// Objective-C file with clang's size, alignment and offset of every bound
/// struct and the value of every bound enumerator and integer macro, and a
/// Stainless program that computes the same from the bindings and names
/// every one that differs. Both are built for the same target, so the case
/// checks whichever the suite runs as.
/// </summary>
public static partial class LayoutCase
{
    /// <summary>
    /// The generator's imports, which name each header by its path in the SDK
    /// it read, as the SDK-relative imports a machine whose SDK lives elsewhere
    /// can compile: <c>&lt;ARKit/session.h&gt;</c>, and a subframework's header
    /// through its parent, <c>&lt;Carbon/../Frameworks/HIToolbox.framework/Headers/Events.h&gt;</c>,
    /// since a subframework is not found by its own name.
    /// </summary>
    public static string Portable(string imports) =>
        HeaderPath().Replace(imports, header =>
            header.Groups[2].Success
                ? $"#import <{header.Groups[1].Value}/../Frameworks/{header.Groups[2].Value}/Headers/{header.Groups[3].Value}>"
                : $"#import <{header.Groups[1].Value}/{header.Groups[3].Value}>");

    [System.Text.RegularExpressions.GeneratedRegex(
        "#import \"[^\"]*/System/Library/Frameworks/([^/\"]+)\\.framework/(?:Frameworks/([^/\"]+\\.framework)/)?Headers/([^\"]+)\"")]
    private static partial System.Text.RegularExpressions.Regex HeaderPath();

    /// <summary>How many checks go in one Stainless function, which keeps each one quick to compile.</summary>
    private const int ChecksPerFunction = 400;

    public static void Write(
        string directory, string output, IReadOnlyList<string> frameworks,
        List<Emitted> arm, List<Emitted> intel, IReadOnlyDictionary<string, string> includes)
    {
        // Only what both targets bound: the case runs as either. Each check
        // is compiled with the headers of the framework whose translation
        // wrote it, a file each: every framework's headers compile alone, and
        // not all of them together -- OpenGL's gl3.h refuses CGLMacro.h.
        var bothTargets = intel.Select(e => (e.Owner, e.Key)).ToHashSet();
        var bound = arm.Where(e => bothTargets.Contains((e.Owner, e.Key))).ToList();
        var groups = frameworks
            .Select(f => (Framework: f, Checks: bound.Where(e => e.Source == f).SelectMany(e => e.Checks).ToList()))
            .Where(g => g.Checks.Count > 0)
            .ToList();
        var checks = groups.SelectMany(g => g.Checks).ToList();

        var modules = arm.Select(e => e.Owner).Distinct().Order(StringComparer.Ordinal).ToList();

        Directory.CreateDirectory(directory);
        foreach (string stale in Directory.GetFiles(directory)) File.Delete(stale);

        for (int g = 0; g < groups.Count; g++)
        {
            var part = new StringBuilder();
            part.Append($"// Generated by tools/Stainless.Bindgen: what clang says each declaration {groups[g].Framework}'s\n");
            part.Append("// headers bound is. Do not edit; regenerate with tools/bindgen.sh.\n\n");
            part.Append(Portable(includes[groups[g].Framework]));
            part.Append($"\nconst long long sl_layout_{g}[] = {{\n");
            foreach (var (cExpression, _) in groups[g].Checks)
                part.Append($"    (long long)({cExpression}),\n");
            part.Append("};\n");
            File.WriteAllText(Path.Combine(directory, $"layout_{groups[g].Framework}.m"), part.ToString());
        }

        var c = new StringBuilder();
        c.Append("// Generated by tools/Stainless.Bindgen: the checks of every layout_*.m, in order.\n");
        c.Append("// Do not edit; regenerate with tools/bindgen.sh.\n\n");
        for (int g = 0; g < groups.Count; g++)
            c.Append($"extern const long long sl_layout_{g}[];\n");
        c.Append("\nstatic const long long *const sl_parts[] = {\n");
        for (int g = 0; g < groups.Count; g++) c.Append($"    sl_layout_{g},\n");
        c.Append("};\n\nstatic const long long sl_counts[] = {\n");
        foreach (var group in groups) c.Append($"    {group.Checks.Count},\n");
        c.Append("};\n\n");
        c.Append($"long long SLLayoutCount(void) {{ return {checks.Count}; }}\n\n");
        c.Append("long long SLLayoutValue(long long index)\n{\n");
        c.Append("    int g = 0;\n");
        c.Append("    while (index >= sl_counts[g]) index -= sl_counts[g++];\n");
        c.Append("    return sl_parts[g][index];\n}\n");
        File.WriteAllText(Path.Combine(directory, "layout.m"), c.ToString());

        var mine = new StringBuilder();
        mine.Append("// Generated by tools/Stainless.Bindgen: every bound struct's size, alignment and\n");
        mine.Append("// offsets and every bound constant's value, against what clang says in layout.m.\n");
        mine.Append("// Do not edit; regenerate with tools/bindgen.sh.\n");
        mine.Append("module BindingsLayout;\n\n");
        mine.Append("import Standard.Console;\n");
        foreach (string module in modules) mine.Append($"import {Writer.ModuleOf(module)};\n");
        mine.Append("\nextern \"C\"\n{\n    long SLLayoutCount();\n    long SLLayoutValue(long index);\n}\n\n");
        mine.Append("static long Checked = 0;\nstatic long Wrong = 0;\n\n");
        mine.Append("void Expect(long mine, String what)\n{\n");
        mine.Append("    long theirs = SLLayoutValue(Checked);\n");
        mine.Append("    if (mine != theirs)\n    {\n");
        mine.Append("        Console.WriteLine($\"{what}: the binding says {mine}, clang says {theirs}\");\n");
        mine.Append("        Wrong++;\n    }\n\n    Checked++;\n}\n");

        int functions = (checks.Count + ChecksPerFunction - 1) / ChecksPerFunction;
        for (int f = 0; f < functions; f++)
        {
            mine.Append($"\nvoid Check{f}()\n{{\n");
            foreach (var (cExpression, expression) in checks.Skip(f * ChecksPerFunction).Take(ChecksPerFunction))
                mine.Append($"    Expect((long){expression}, \"{cExpression}\");\n");
            mine.Append("}\n");
        }

        mine.Append("\nint Main()\n{\n");
        for (int f = 0; f < functions; f++) mine.Append($"    Check{f}();\n");
        mine.Append("    if (Checked != SLLayoutCount())\n");
        mine.Append("        Console.WriteLine($\"checked {Checked} and clang has {SLLayoutCount()}\");\n");
        mine.Append("    Console.WriteLine($\"{Checked} checks, {Wrong} wrong\");\n");
        mine.Append("    return 0;\n}\n");
        File.WriteAllText(Path.Combine(directory, "layout.sl"), mine.ToString());

        string relative = Path.GetRelativePath(Path.Combine(directory, "..", "..", ".."), output).Replace('\\', '/');
        File.WriteAllText(Path.Combine(directory, "sources.txt"),
            string.Concat(modules.Select(m => $"{relative}/{m}\n")));
        File.WriteAllText(Path.Combine(directory, "platform.txt"), "macos\n");
        File.WriteAllText(Path.Combine(directory, "expected.txt"), $"{checks.Count} checks, 0 wrong\n");
    }
}
