using System.Globalization;
using System.Text;

namespace Stainless.Bindgen;

/// <summary>
/// The end-to-end case that holds the Objective-C bindings to the runtime:
/// every bound class is asked for by name, and every message a class is
/// declared to answer is asked of the class. What appeared in a macOS later
/// than the one running is not asked. A binding whose class or selector the
/// runtime has never heard of is a message no object answers.
/// </summary>
public static class RuntimeCase
{
    public static void Write(string directory, string output, List<Emitted> arm, IReadOnlySet<string> known)
    {
        var checks = arm.SelectMany(e => e.Runtime)
            .Where(c => !known.Contains(Describe(c)))
            .Distinct()
            .OrderBy(c => c.Class, StringComparer.Ordinal)
            .ThenBy(c => c.Selector, StringComparer.Ordinal)
            .ToList();

        var modules = arm.Select(e => e.Owner).Distinct().Order(StringComparer.Ordinal).ToList();

        Directory.CreateDirectory(directory);
        foreach (string stale in Directory.GetFiles(directory)) File.Delete(stale);

        var m = new StringBuilder();
        m.Append("// Generated by tools/Stainless.Bindgen: every bound Objective-C class and message,\n");
        m.Append("// asked of the runtime. Do not edit; regenerate with tools/bindgen.sh.\n\n");
        m.Append("#import <Foundation/Foundation.h>\n#import <objc/runtime.h>\n\n");
        m.Append("typedef struct { const char *cls; const char *sel; int instance; int major; int minor; } SLRuntimeCheck;\n\n");
        m.Append("static const SLRuntimeCheck sl_checks[] = {\n");
        foreach (var check in checks)
        {
            var (major, minor) = Version(check.Introduced);
            string selector = check.Selector is null ? "NULL" : $"\"{check.Selector}\"";
            m.Append($"    {{ \"{check.Class}\", {selector}, {(check.IsInstance ? 1 : 0)}, {major}, {minor} }},\n");
        }
        m.Append("};\n\n");
        m.Append("""
            // Every class the runtime has, read once.
            static Class *sl_classes;
            static int sl_class_count;

            // Whether the class, or a class derived from it, answers the
            // selector: an abstract class's alloc may make a private subclass
            // that answers what the class declares, as Metal's descriptors and
            // Foundation's clusters do.
            static BOOL SLAnswers(Class cls, SEL sel, int instance)
            {
                if (class_respondsToSelector(instance ? cls : object_getClass((id)cls), sel)) return YES;

                if (sl_classes == NULL) {
                    sl_class_count = objc_getClassList(NULL, 0);
                    sl_classes = (Class *)malloc(sizeof(Class) * (size_t)sl_class_count);
                    sl_class_count = objc_getClassList(sl_classes, sl_class_count);
                }

                for (int i = 0; i < sl_class_count; i++)
                    for (Class base = class_getSuperclass(sl_classes[i]); base != Nil; base = class_getSuperclass(base))
                        if (base == cls) {
                            Class derived = sl_classes[i];
                            if (class_respondsToSelector(instance ? derived : object_getClass((id)derived), sel)) return YES;
                            break;
                        }
                return NO;
            }

            // What is missing, a line each; and the number missing.
            long SLRuntimeMissing(void)
            {
                NSOperatingSystemVersion running = NSProcessInfo.processInfo.operatingSystemVersion;
                long missing = 0;
                for (size_t i = 0; i < sizeof(sl_checks) / sizeof(sl_checks[0]); i++) {
                    const SLRuntimeCheck *check = &sl_checks[i];
                    if (check->major > running.majorVersion ||
                        (check->major == running.majorVersion && check->minor > running.minorVersion))
                        continue;

                    Class cls = objc_getClass(check->cls);
                    if (cls == Nil) {
                        if (check->sel == NULL) { printf("no class %s\n", check->cls); missing++; }
                        continue;
                    }
                    if (check->sel == NULL) continue;

                    if (!SLAnswers(cls, sel_registerName(check->sel), check->instance)) {
                        printf("%c[%s %s] is not answered\n", check->instance ? '-' : '+', check->cls, check->sel);
                        missing++;
                    }
                }
                return missing;
            }

            """);
        File.WriteAllText(Path.Combine(directory, "runtime.m"), m.ToString());

        var main = new StringBuilder();
        main.Append("// Generated by tools/Stainless.Bindgen: asks the runtime for every bound class and\n");
        main.Append("// message, linked with every bound framework. Do not edit; regenerate with tools/bindgen.sh.\n");
        main.Append("module BindingsRuntime;\n\n");
        main.Append("import Standard.Console;\n\n");
        main.Append("extern \"C\" long SLRuntimeMissing();\n\n");
        main.Append("int Main()\n{\n");
        main.Append("    long missing = SLRuntimeMissing();\n");
        main.Append($"    Console.WriteLine(missing == 0 ? \"{checks.Count} checks, none missing\" : $\"{{missing}} missing\");\n");
        main.Append("    return 0;\n}\n");
        File.WriteAllText(Path.Combine(directory, "runtime.sl"), main.ToString());

        string relative = Path.GetRelativePath(Path.Combine(directory, "..", "..", ".."), output).Replace('\\', '/');
        File.WriteAllText(Path.Combine(directory, "sources.txt"),
            string.Concat(modules.Select(module => $"{relative}/{module}\n")));
        File.WriteAllText(Path.Combine(directory, "platform.txt"), "macos\n");
        File.WriteAllText(Path.Combine(directory, "expected.txt"), $"{checks.Count} checks, none missing\n");
    }

    /// <summary>How a check is named in the list of those known not to answer.</summary>
    public static string Describe(RuntimeCheck check) =>
        check.Selector is null
            ? check.Class
            : $"{(check.IsInstance ? '-' : '+')}[{check.Class} {check.Selector}]";

    private static (int Major, int Minor) Version(string? introduced)
    {
        if (introduced is null) return (0, 0);
        var parts = introduced.Split('.');
        int major = int.Parse(parts[0], CultureInfo.InvariantCulture);
        int minor = parts.Length > 1 ? int.Parse(parts[1], CultureInfo.InvariantCulture) : 0;
        return (major, minor);
    }
}
