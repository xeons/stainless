using System.Text;
using Stainless.Binding;
using Stainless.Syntax;

namespace Stainless.Emit;

/// <summary>
/// Writes a C header describing a shared library's exported surface.
///
/// This is possible only because a Stainless <c>struct</c> is a C struct and an
/// <c>export "C"</c> function uses the platform C convention: the header is a
/// restatement of what is already true, not a marshalling layer.
/// </summary>
public static class CHeaderWriter
{
    public static string Write(BoundProgram program, string headerPath)
    {
        var exports = program.Modules
            .SelectMany(m => m.Functions)
            .Where(f => f.Linkage == LinkageKind.ExportC)
            .GroupBy(f => f.Name, StringComparer.Ordinal)
            .Select(g => g.First())
            .OrderBy(f => f.Name, StringComparer.Ordinal)
            .ToList();

        // Only the structs an export actually mentions, in an order C accepts.
        var structs = new List<StructTypeSymbol>();
        var seen = new HashSet<StructTypeSymbol>();
        foreach (var function in exports)
        {
            Collect(function.ReturnType, structs, seen);
            foreach (var parameter in function.Parameters) Collect(parameter.Type, structs, seen);
        }

        string guard = GuardName(headerPath);
        var sb = new StringBuilder();

        sb.AppendLine("/*");
        sb.AppendLine(" * Generated by the Stainless compiler. Do not edit.");
        sb.AppendLine(" *");
        sb.AppendLine(" * Declares the exported surface of this library. The types below are the");
        sb.AppendLine(" * same bytes Stainless uses, so nothing here marshals or converts.");
        sb.AppendLine(" */");
        sb.AppendLine();
        sb.AppendLine($"#ifndef {guard}");
        sb.AppendLine($"#define {guard}");
        sb.AppendLine();
        sb.AppendLine("#include <stdbool.h>");
        sb.AppendLine("#include <stddef.h>");
        sb.AppendLine("#include <stdint.h>");
        sb.AppendLine();
        sb.AppendLine("#ifdef __cplusplus");
        sb.AppendLine("extern \"C\" {");
        sb.AppendLine("#endif");
        sb.AppendLine();

        foreach (var structType in structs)
        {
            sb.AppendLine($"typedef struct {CName(structType)} {{");
            foreach (var field in structType.Fields)
                sb.AppendLine($"    {Declarator(field.Type, field.Name)};");
            sb.AppendLine($"}} {CName(structType)};");
            sb.AppendLine();
        }

        if (exports.Count == 0)
        {
            sb.AppendLine("/* This library exports nothing. Mark a function 'export \"C\"'. */");
            sb.AppendLine();
        }

        foreach (var function in exports)
        {
            var parameters = function.Parameters
                .Where(p => !p.IsThis)
                .Select(p => Declarator(p.Type, p.Name))
                .ToList();

            if (function.IsVariadic) parameters.Add("...");
            string list = parameters.Count == 0 ? "void" : string.Join(", ", parameters);

            sb.AppendLine($"{TypeName(function.ReturnType)} {function.Name}({list});");
        }

        sb.AppendLine();
        sb.AppendLine("#ifdef __cplusplus");
        sb.AppendLine("}");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine($"#endif /* {guard} */");
        return sb.ToString();
    }

    /// <summary>Gathers structs depth first, so a nested one is declared before its user.</summary>
    private static void Collect(
        TypeSymbol type, List<StructTypeSymbol> ordered, HashSet<StructTypeSymbol> seen)
    {
        switch (type)
        {
            case StructTypeSymbol structType when seen.Add(structType):
                foreach (var field in structType.Fields) Collect(field.Type, ordered, seen);
                ordered.Add(structType);
                break;

            case PointerTypeSymbol pointer:
                Collect(pointer.Element, ordered, seen);
                break;
        }
    }

    private static string GuardName(string headerPath)
    {
        string name = Path.GetFileName(headerPath);
        var guard = new string(name.Select(c => char.IsLetterOrDigit(c) ? char.ToUpperInvariant(c) : '_')
            .ToArray());
        return char.IsDigit(guard.FirstOrDefault()) ? "H_" + guard : guard;
    }

    private static string CName(NamedTypeSymbol type) => Mangler.SymbolSafe(type.QualifiedName);

    /// <summary>A C declaration of <paramref name="name"/> with the given type.</summary>
    private static string Declarator(TypeSymbol type, string name) => $"{TypeName(type)} {name}";

    private static string TypeName(TypeSymbol type) => type switch
    {
        PrimitiveTypeSymbol primitive => primitive.Kind switch
        {
            PrimitiveKind.Void => "void",
            PrimitiveKind.Bool => "bool",
            PrimitiveKind.Char => "char",
            PrimitiveKind.SByte => "int8_t",
            PrimitiveKind.Short => "int16_t",
            PrimitiveKind.Int => "int32_t",
            PrimitiveKind.Long => "int64_t",
            PrimitiveKind.NInt => "intptr_t",
            PrimitiveKind.Byte => "uint8_t",
            PrimitiveKind.UShort => "uint16_t",
            PrimitiveKind.UInt => "uint32_t",
            PrimitiveKind.ULong => "uint64_t",
            PrimitiveKind.NUInt => "size_t",
            PrimitiveKind.Float => "float",
            _ => "double",
        },

        PointerTypeSymbol pointer => TypeName(pointer.Element) + "*",
        StructTypeSymbol structType => CName(structType),

        // A managed reference has no C spelling. It crosses as an opaque handle,
        // which the caller must not free or dereference.
        _ => "void*",
    };
}
